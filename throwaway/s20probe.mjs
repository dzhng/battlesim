import { chromium } from "playwright";
const [url, out, wait] = process.argv.slice(2);
const browser = await chromium.launch({ channel: "chromium", args: ["--enable-unsafe-webgpu", "--enable-features=WebGPU", "--mute-audio"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on("console", (m) => { if (m.type() === "error" || m.type() === "warning") errors.push(`${m.type()}: ${m.text()}`.slice(0, 400)); });
page.on("pageerror", (e) => errors.push(`pageerror: ${e.message}\n${e.stack}`.slice(0, 800)));
await page.goto(url);
const run = page.getByRole("button", { name: "Run graphics test" });
if (await run.count()) await run.click();
await page.waitForTimeout(Number(wait ?? 30000));
await page.screenshot({ path: out });
const stats = await page.evaluate(() => { try { const s = window.__lab?.stats?.(); return s && { models: s.models, effects: s.effects }; } catch (e) { return String(e); } });
for (const e of errors.slice(0, 12)) console.log(e.slice(0, 300));
console.log(JSON.stringify(stats));
await browser.close();
